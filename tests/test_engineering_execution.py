"""Generated outputs, explicit inputs and failures through actual workflow execution."""
import json

from workflow_fixture import WorkflowFixture
from evolve_core.apply import implement
from evolve_core.errors import EvolveError
from evolve_core.package import digest
from evolve_core.work import fingerprint


class EngineeringExecutionTests(WorkflowFixture):
    def definition(self):
        return json.loads(self.rows('SELECT definition_json FROM tasks WHERE id=?',
                                    (self.plan['task_id'],))[0]['definition_json'])

    def test_typescript_incremental_cache_does_not_invalidate_source_checks(self):
        test = self.root / 'test_total.py'
        test.write_text(test.read_text() + '\nfrom pathlib import Path\n'
                        'Path("tsconfig.tsbuildinfo").write_text("generated by tsc")\n')
        request = self.apply_request()
        request['input']['observations'] = {'test_total.py': digest(test.read_bytes())}
        result = implement(self.root, request)
        self.assertEqual(result['outcome'], 'implemented')
        self.assertEqual(result['task_checks'][0]['status'], 'passed')

    def test_explicit_cache_scope_remains_part_of_fingerprint(self):
        path = self.root / 'tsconfig.tsbuildinfo'
        path.write_text('original')
        definition = {**self.definition(), 'scope': ['tsconfig.tsbuildinfo']}
        before = fingerprint(self.root, definition)
        path.write_text('changed')
        after = fingerprint(self.root, definition)
        self.assertNotEqual(before['digest'], after['digest'])
        self.assertNotEqual(before['scope'], after['scope'])

    def test_explicit_simple_context_in_generated_directory_is_protected(self):
        path = self.root / '.next' / 'BUILD_ID'
        path.parent.mkdir()
        path.write_text('original')
        definition = {**self.definition(), 'context': {'.next/BUILD_ID': digest(path.read_bytes())}}
        before = fingerprint(self.root, definition)
        path.write_text('changed')
        self.assertNotEqual(before['digest'], fingerprint(self.root, definition)['digest'])

    def test_gitignore_does_not_hide_source_changes(self):
        (self.root / '.gitignore').write_text('private-input.txt\n')
        path = self.root / 'private-input.txt'
        path.write_text('original')
        before = fingerprint(self.root, self.definition())
        path.write_text('changed')
        self.assertNotEqual(before['digest'], fingerprint(self.root, self.definition())['digest'])

    def test_configured_generated_path_is_ignored_unless_explicitly_protected(self):
        config = self.root / 'evolve/config.toml'
        config.write_text(config.read_text().replace('policy = "impact"', 'policy = "impact"\ngenerated_paths = ["local-cache"]'))
        path = self.root / 'local-cache' / 'result.json'
        path.parent.mkdir()
        path.write_text('first')
        definition = self.definition()
        before = fingerprint(self.root, definition)
        protected = fingerprint(self.root, {**definition, 'context': {'local-cache/result.json': None}})
        path.write_text('second')
        self.assertEqual(before['digest'], fingerprint(self.root, definition)['digest'])
        self.assertNotEqual(protected['digest'], fingerprint(self.root, {**definition, 'context': {'local-cache/result.json': None}})['digest'])

    def test_source_mutation_during_check_reports_paths_check_and_written_effects(self):
        test = self.root / 'test_total.py'
        test.write_text(test.read_text() + '\nfrom pathlib import Path\n'
                        'Path("unexpected.txt").write_text("actual check side effect")\n')
        request = self.apply_request()
        request['input']['observations'] = {'test_total.py': digest(test.read_bytes())}
        with self.assertRaises(EvolveError) as caught:
            implement(self.root, request)
        self.assertEqual(caught.exception.code, 'WORKSPACE_CHANGED')
        details = caught.exception.details
        self.assertEqual(details['workspace_change']['check_id'], 'unit')
        self.assertEqual(details['workspace_change']['paths'][0]['path'], 'unexpected.txt')
        self.assertEqual(details['workspace_change']['paths'][0]['change'], 'created')
        self.assertEqual(details['execution']['business_files'], 'committed')
        self.assertTrue(details['execution']['checks_only_continuation_available'])
        self.assertIn('return sum(values)', (self.root / 'total.py').read_text())
        self.assertEqual(self.rows('SELECT state FROM tasks')[0]['state'], 'in_progress')
